function Add-SvgRoad {
	param([object]$Road, [System.Text.StringBuilder]$Builder)
	$road = $Road
	$center = Get-SvgPoint $road.centerMeters[0] $road.centerMeters[1]
	$rectWidth = $road.sizeMeters[0] * 1.82
	$rectHeight = $road.sizeMeters[1] * 1.82
	$fill = if ($road.kind -eq "external_street") { "#30383f" } else { "#a2a8a8" }
	$angle = $road.rotationDegrees
	$roadLabel = [System.Security.SecurityElement]::Escape($road.label)
	[void]$Builder.AppendLine("<g transform=`"rotate($angle $($center.X) $($center.Y))`"><rect x=`"$([Math]::Round($center.X - $rectWidth / 2, 2))`" y=`"$([Math]::Round($center.Y - $rectHeight / 2, 2))`" width=`"$([Math]::Round($rectWidth, 2))`" height=`"$([Math]::Round($rectHeight, 2))`" rx=`"2`" fill=`"$fill`"/>")
	if ($road.displayLabel -ne $false -and -not [string]::IsNullOrWhiteSpace($road.label)) {
		[void]$Builder.AppendLine("<text x=`"$($center.X)`" y=`"$($center.Y + 4)`" text-anchor=`"middle`" fill=`"#e3e7e8`" font-family=`"Arial,sans-serif`" font-size=`"11`">$roadLabel</text>")
	}
	[void]$Builder.AppendLine("</g>")
}

