local CampusManifest = $luauTable
return table.freeze(CampusManifest)
"@.TrimStart()
	[System.IO.File]::WriteAllText($modulePath, $luauSource, $utf8NoBom)
}

function Get-SvgPoint {
	param([double]$X, [double]$Z)
	$minimumX = -35.0
	$minimumZ = -32.0
	$scale = 1.82
	$left = 70.0
	$bottom = 710.0
	return @{
		X = [Math]::Round($left + ($X - $minimumX) * $scale, 2)
		Y = [Math]::Round($bottom - ($Z - $minimumZ) * $scale, 2)
	}
}

