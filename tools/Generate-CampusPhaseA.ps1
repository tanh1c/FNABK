function ConvertTo-LuauValue {
	param([object]$Value, [int]$Indent = 0)

	if ($null -eq $Value) { return "nil" }
	if ($Value -is [bool]) { return $Value.ToString().ToLowerInvariant() }
	if ($Value -is [string]) {
		$escaped = $Value.Replace("\", "\\").Replace('"', '\"').Replace("`r", "\r").Replace("`n", "\n")
		return '"' + $escaped + '"'
	}
	if ($Value -is [System.Collections.IDictionary]) {
		$properties = @($Value.GetEnumerator())
		$entries = foreach ($property in $properties) {
			$key = ConvertTo-LuauValue ([string]$property.Key) ($Indent + 1)
			$entryValue = ConvertTo-LuauValue $property.Value ($Indent + 1)
			("`t" * ($Indent + 1)) + "[$key] = $entryValue"
		}
		if ($entries.Count -eq 0) { return "{}" }
		return "{`n" + ($entries -join ",`n") + "`n" + ("`t" * $Indent) + "}"
	}
	if ($Value -is [System.Management.Automation.PSCustomObject]) {
		$entries = foreach ($property in $Value.PSObject.Properties) {
			$key = ConvertTo-LuauValue $property.Name ($Indent + 1)
			$entryValue = ConvertTo-LuauValue $property.Value ($Indent + 1)
			("`t" * ($Indent + 1)) + "[$key] = $entryValue"
		}
		if ($entries.Count -eq 0) { return "{}" }
		return "{`n" + ($entries -join ",`n") + "`n" + ("`t" * $Indent) + "}"
	}
	if ($Value -is [System.Collections.IEnumerable] -and $Value -isnot [string]) {
		$items = foreach ($item in $Value) {
			("`t" * ($Indent + 1)) + (ConvertTo-LuauValue $item ($Indent + 1))
		}
		if ($items.Count -eq 0) { return "{}" }
		return "{`n" + ($items -join ",`n") + "`n" + ("`t" * $Indent) + "}"
	}
	if ($Value -is [System.IFormattable]) {
		return $Value.ToString($null, [System.Globalization.CultureInfo]::InvariantCulture)
	}
	return [string]$Value
}

 $utf8NoBom = New-Object -TypeName System.Text.UTF8Encoding -ArgumentList @($false)
if (-not $SkipLuauModule) {
